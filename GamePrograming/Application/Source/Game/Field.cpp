#include "framework.h"
#include "DirectX/DirectX.h"
#include "Game/Physics.h"

#include "Game/Field.h"

/****************************************************
* フィールド初期化
*****************************************************/
Field::Field() {
	m_ground = new Ground();
}

/****************************************************
* フィールド終了
*****************************************************/
Field::~Field() {
	if (m_ground) delete m_ground;
}

/****************************************************
* フィールド更新
*****************************************************/
void Field::Update() {
	m_ground->Update();
}

/****************************************************
* フィールド描画
*****************************************************/
void Field::Draw() {
	m_ground->Draw();
}
